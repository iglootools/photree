"""
Generate the field tables in docs/config-reference.md from the config models.

Reads the dataclasses in ``photree/config/protocol.py`` (each field's TOML key,
type, default, and the description in its ``metadata``) and splices one table
per TOML table between the ``CONFIGREF`` marker comments. The prose around the
markers stays hand-written.

Usage:
    python build-scripts/configdocs.py          # regenerate the tables
    python build-scripts/configdocs.py --check  # exit non-zero if out of date

Hand-rolled rather than a library: the config models are plain dataclasses,
and the Pydantic doc generators are MkDocs or Sphinx plugins with no ``--check``
mode to run as a lint.
"""

import dataclasses
import typing
from enum import StrEnum
from functools import reduce
from pathlib import Path
from types import NoneType, UnionType
from typing import Annotated

import typer
from rich.console import Console

from photree.config.protocol import ExporterProfile, ImporterConfig, toml_key

CONFIG_REFERENCE_MD = (
    Path(__file__).resolve().parent.parent / "docs" / "config-reference.md"
)

# Marker name -> the dataclass whose fields are that TOML table's keys.
_TABLES: dict[str, type] = {
    "CONFIGREF:IMPORTER": ImporterConfig,
    "CONFIGREF:EXPORTER_PROFILE": ExporterProfile,
}

_stdout = Console(soft_wrap=True, highlight=False)
_stderr = Console(stderr=True, soft_wrap=True, highlight=False)


def _begin_marker(name: str) -> str:
    return (
        f"<!-- BEGIN {name} (auto-generated by: mise run configdocs"
        " — do not edit manually) -->"
    )


def _end_marker(name: str) -> str:
    return f"<!-- END {name} -->"


def _non_optional(annotation: object) -> object:
    """Return *annotation* without its ``| None``."""
    members = typing.get_args(annotation) if isinstance(annotation, UnionType) else ()
    match [m for m in members if m is not NoneType]:
        case [inner]:
            return inner
        case _:
            return annotation


def _is_enum(annotation: object) -> typing.TypeIs[type[StrEnum]]:
    return isinstance(annotation, type) and issubclass(annotation, StrEnum)


_TYPE_NAMES: dict[object, str] = {Path: "string (path)", str: "string"}


def _format_type(annotation: object, *, required: bool) -> str:
    base = "string" if _is_enum(annotation) else _TYPE_NAMES.get(annotation)
    if base is None:
        # The loader reads only strings today; a new value type needs a name here
        # rather than a guess.
        _stderr.print(
            f"No reference type name for the config annotation {annotation!r}:"
            " add one to _TYPE_NAMES in build-scripts/configdocs.py.",
            markup=False,
        )
        raise typer.Exit(code=1)
    else:
        return f"{base}, **required**" if required else base


def _format_default(field: dataclasses.Field[object]) -> str:
    shown = field.metadata.get("shown_default")
    match field.default:
        case _ if shown is not None:
            return f"`{shown}`"
        case dataclasses.MISSING:
            return "—"
        case StrEnum() as value:
            return f"`{value.value}`"
        case None:
            return "—"
        case value:
            return f"`{value}`"


def _format_description(field: dataclasses.Field[object], annotation: object) -> str:
    description: str = field.metadata["description"]
    allowed = (
        [" Allowed values: " + ", ".join(f"`{e.value}`" for e in annotation) + "."]
        if _is_enum(annotation)
        else []
    )
    return "".join([description, *allowed])


def _generate_table(config_cls: type) -> str:
    """Return the Markdown table of *config_cls*'s TOML keys."""
    hints = typing.get_type_hints(config_cls)

    def row(field: dataclasses.Field[object]) -> str:
        annotation = _non_optional(hints[field.name])
        required = field.default is dataclasses.MISSING
        return (
            f"| `{toml_key(field.name)}`"
            f" | {_format_type(annotation, required=required)}"
            f" | {_format_default(field)}"
            f" | {_format_description(field, annotation)} |"
        )

    return "\n".join(
        [
            "| Key | Type | Default | Description |",
            "|---|---|---|---|",
            *(row(f) for f in dataclasses.fields(config_cls)),
        ],
    )


def _splice_section(content: str, name: str, body: str) -> str:
    """Replace what lies between *name*'s BEGIN and END markers with *body*."""
    begin = _begin_marker(name)
    end = _end_marker(name)
    begin_idx = content.find(begin)
    end_idx = content.find(end)
    if begin_idx == -1 or end_idx == -1:
        _stderr.print(
            f"Markers for {name} not found in {CONFIG_REFERENCE_MD}. Expected:\n"
            f"  {begin}\n  {end}",
            markup=False,
        )
        raise typer.Exit(code=1)
    else:
        return f"{content[:begin_idx]}{begin}\n{body}\n{content[end_idx:]}"


def _render(content: str) -> str:
    """Return *content* with every generated table regenerated."""
    return reduce(
        lambda acc, table: _splice_section(acc, table[0], _generate_table(table[1])),
        _TABLES.items(),
        content,
    )


app = typer.Typer(add_completion=False)


@app.command()
def main(
    *,
    check: Annotated[
        bool,
        typer.Option("--check", help="Exit non-zero if the tables are out of date."),
    ] = False,
) -> None:
    """Regenerate, or check, the field tables in docs/config-reference.md."""
    current = CONFIG_REFERENCE_MD.read_text(encoding="utf-8")
    expected = _render(current)
    match (check, current == expected):
        case (True, True):
            _stdout.print(f"{CONFIG_REFERENCE_MD.name} is up to date.", markup=False)
        case (True, False):
            _stderr.print(
                f"The config field tables in {CONFIG_REFERENCE_MD.name} are out of"
                " date. Run `mise run configdocs` to regenerate them.",
                markup=False,
            )
            raise typer.Exit(code=1)
        case _:
            CONFIG_REFERENCE_MD.write_text(expected, encoding="utf-8")
            _stdout.print(
                f"Updated the config field tables in {CONFIG_REFERENCE_MD.name}.",
                markup=False,
            )


if __name__ == "__main__":
    app()
